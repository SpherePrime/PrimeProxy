  const LANGS = ["ru", "uk", "en"];

  function format(template, params) {
    let out = template || "";
    if (!params) return out;
    for (const key of Object.keys(params)) {
      out = out.split("{" + key + "}").join(String(params[key]));
    }
    return out;
  }

  let lang = "en";

  function resolveLang(preferred) {
    if (preferred && LANGS.indexOf(preferred) !== -1) return preferred;
    const nav = (navigator.language || "en").toLowerCase();
    const base = nav.split("-")[0] || "en";
    if (LANGS.indexOf(base) !== -1) return base;
    if (base === "be" || base === "pl") return "uk";
    if (base === "ua") return "uk";
    return "en";
  }

  function current() {
    return lang;
  }

  function setLang(value) {
    lang = resolveLang(value);
    return lang;
  }

  function t(key, params) {
    const cat = catalogs[lang] || catalogs.en;
    return format(cat[key] !== undefined ? cat[key] : (catalogs.en[key] !== undefined ? catalogs.en[key] : key), params);
  }

  // Replace each key; supports value interpolation via {...}
  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    scope.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
  }

  window.I18n = {
    setLang: setLang,
    current: current,
    resolveLang: resolveLang,
    t: t,
    apply: apply,
    catalogs: catalogs,
  };
