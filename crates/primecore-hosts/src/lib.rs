//! Порт чистой логики `src/hosts/hosts.py` — управляемый блок PrimeBypass
//! в системном hosts. Перенесено всё детерминированное: разбор строк,
//! снятие/вставка блока (с узнаванием блока прежней версии программы),
//! чужие строки, отфильтровка адресов, сверка блоков. Файловый I/O,
//! командные утилиты Windows (`icacls` и пр.), каталог IP-профилей,
//! проверка посредников и Adobe-блок остаются в Python-версии и дверях
//! (сERVER/electron), им нужен I/O и каталог адресов.
//!
//! Свой блок помечается маркерами `# >>> primebypass:hosts managed …`;
//! блоки старых версий (`primeproxy`, `zapretgui`) узнаваемы и
//! перезаписываются — это данные прошлого, не бренд.

/// Строки hosts как в `content.splitlines(keepends=True)`: каждый элемент
/// — строка файла со своим переводом строки.
pub type Lines = Vec<String>;

pub const MANAGED_HOSTS_BEGIN: &str = "# >>> primebypass:hosts managed begin >>>";
pub const MANAGED_HOSTS_END: &str = "# <<< primebypass:hosts managed end <<<";
/// Блок, записанный прежней версией: узнаваем и перезаписывается новым.
pub const MANAGED_HOSTS_LEGACY_BEGIN: &str = "# >>> primeproxy:hosts managed begin >>>";
pub const MANAGED_HOSTS_LEGACY_END: &str = "# <<< primeproxy:hosts managed end <<<";
pub const MANAGED_HOSTS_LEGACY_BEGIN_1: &str = "# >>> zapretgui:hosts managed begin >>>";
pub const MANAGED_HOSTS_LEGACY_END_1: &str = "# <<< zapretgui:hosts managed end <<<";

pub const MANAGED_HOSTS_BEGIN_MARKERS: [&str; 3] = [
    MANAGED_HOSTS_BEGIN,
    MANAGED_HOSTS_LEGACY_BEGIN,
    MANAGED_HOSTS_LEGACY_BEGIN_1,
];
pub const MANAGED_HOSTS_END_MARKERS: [&str; 3] = [
    MANAGED_HOSTS_END,
    MANAGED_HOSTS_LEGACY_END,
    MANAGED_HOSTS_LEGACY_END_1,
];
pub const MANAGED_HOSTS_NOTICE: &str =
    "# Generated by PrimeBypass. Do not edit this block manually.";

/// Блоки других возможностей программы в том же файле: у них свой
/// хозяин, их строки не трогаются. Все три префикса «наш»: текущее имя,
/// PrimeProxy (выпуски до переименования) и zapretgui (старые выпуски).
pub const OTHER_BLOCKS: [(&str, &str); 7] = [
    ("# >>> primebypass:", "# <<< primebypass:"),
    ("# >>> primeproxy:", "# <<< primeproxy:"),
    ("# >>> zapretgui:", "# <<< zapretgui:"),
    ("# MAX BLOCKED BY PRIMEBYPASS", "# END MAX BLOCK"),
    ("# MAX BLOCKED BY PRIMEPROXY", "# END MAX BLOCK"),
    ("# MAX BLOCKED BY ZAPRET GUI", "# END MAX BLOCK"),
    // У блока Telegram Proxy нет конечной метки: он идёт до пустой строки
    // или до конца файла.
    ("# --- Telegram Proxy (auto-managed", ""),
];

/// Разбор строки hosts: `ip domain…[ # комментарий]`.
/// Возвращает `(ip, домены, комментарий)`.
pub fn parse_hosts_mapping_line(line: &str) -> Option<(String, Vec<String>, String)> {
    let hash = line.find('#');
    let (mapping_part, comment_part) = match hash {
        Some(index) => (line[..index].trim(), line[index + 1..].trim()),
        None => (line.trim(), ""),
    };
    if mapping_part.is_empty() {
        return None;
    }
    let mut parts = mapping_part.split_ascii_whitespace();
    let ip = parts.next()?;
    let domains: Vec<String> = parts.map(str::to_string).collect();
    if domains.is_empty() {
        return None;
    }
    Some((ip.to_string(), domains, comment_part.to_string()))
}

fn is_end_marker(stripped: &str, markers: &[&str]) -> bool {
    markers.iter().any(|m| *m == stripped)
}

fn begin_marker_hit(stripped: &str) -> bool {
    is_end_marker(stripped, &MANAGED_HOSTS_BEGIN_MARKERS)
}

fn end_marker_hit(stripped: &str) -> bool {
    is_end_marker(stripped, &MANAGED_HOSTS_END_MARKERS)
}

fn lowered(value: &str) -> String {
    value.trim().to_lowercase()
}

/// (domain, ip) в порядке записи.
pub type Rows = Vec<(String, String)>;

/// Удаляет блок программы из hosts. Возвращает строки без него и
/// количество снятых записей (не считая комментариев и пустых строк).
pub fn remove_managed_hosts_block(lines: &Lines) -> (Lines, usize) {
    let mut new_lines = Vec::with_capacity(lines.len());
    let mut removed_entries = 0usize;
    let mut inside_block = false;
    for line in lines {
        let stripped = line.trim();
        if begin_marker_hit(stripped) {
            inside_block = true;
            continue;
        }
        if inside_block {
            if !stripped.is_empty() && !stripped.starts_with('#') {
                removed_entries += 1;
            }
            if end_marker_hit(stripped) {
                inside_block = false;
            }
            continue;
        }
        new_lines.push(line.clone());
    }
    (new_lines, removed_entries)
}

/// Строки (domain, ip), лежащие внутри блока программы.
pub fn iter_managed_hosts_block_rows(lines: &Lines) -> Rows {
    let mut rows = Vec::new();
    let mut inside_block = false;
    for line in lines {
        let stripped = line.trim();
        if begin_marker_hit(stripped) {
            inside_block = true;
            continue;
        }
        if !inside_block {
            continue;
        }
        if end_marker_hit(stripped) {
            break;
        }
        if stripped.is_empty() || stripped.starts_with('#') {
            continue;
        }
        let Some((ip, domains, _)) = parse_hosts_mapping_line(stripped) else {
            continue;
        };
        for domain in domains {
            rows.push((domain, ip.clone()));
        }
    }
    rows
}

fn format_hosts_mapping_line(ip: &str, domains: &[String], comment: &str) -> String {
    let mut line = format!("{ip} {}", domains.join(" "));
    if !comment.is_empty() {
        line.push_str(" # ");
        line.push_str(comment);
    }
    line.push('\n');
    line
}

/// Убирает из чужих строк hosts адреса, которые мешают включённому
/// сервису. Решение владельца 2026-10-14: такие записи удаляются, даже
/// если ручные, — если мешают нашему ресурсу: Windows ставит IPv6
/// впереди блока, и программы попадают на чужой адрес. Мешает строка
/// с именем ведущего сервиса и адресом, которого у сервиса нет.
/// Возвращает (строки файла, убранные записи «адрес имя»). Строки
/// передаются уже без блока программы.
pub fn drop_conflicting_foreign_rows(lines: &Lines, rows: &Rows) -> (Lines, Vec<String>) {
    let mut wanted: std::collections::BTreeMap<String, Vec<String>> =
        std::collections::BTreeMap::new();
    for (domain, ip) in rows {
        let entry = wanted
            .entry(lowered(domain))
            .or_default();
        let key = lowered(ip);
        if !entry.iter().any(|existing| existing == &key) {
            entry.push(key);
        }
    }
    let mut kept: Lines = Vec::with_capacity(lines.len());
    let mut dropped: Vec<String> = Vec::new();
    let mut closing: Option<&'static str> = None;
    for line in lines {
        let stripped = line.trim();
        if let Some(end) = closing {
            kept.push(line.clone());
            if (!end.is_empty() && stripped.starts_with(end))
                || (end.is_empty() && stripped.is_empty())
            {
                closing = None;
            }
            continue;
        }
        if let Some((_, end)) = OTHER_BLOCKS
            .iter()
            .find(|(begin, _)| stripped.starts_with(begin))
        {
            closing = Some(end);
            kept.push(line.clone());
            continue;
        }
        let parsed = if stripped.starts_with('#') {
            None
        } else {
            parse_hosts_mapping_line(line)
        };
        let Some((ip, domains, comment)) = parsed else {
            kept.push(line.clone());
            continue;
        };
        let mut clash: Vec<String> = Vec::new();
        for domain in &domains {
            let Some(allowed) = wanted.get(&lowered(domain)) else {
                continue;
            };
            let ip_key = lowered(&ip);
            if !allowed.iter().any(|wanted_ip| wanted_ip == &ip_key) {
                clash.push(domain.clone());
            }
        }
        if clash.is_empty() {
            kept.push(line.clone());
            continue;
        }
        for domain in &clash {
            dropped.push(format!("{ip} {domain}"));
        }
        let rest: Vec<String> = domains
            .iter()
            .filter(|domain| !clash.iter().any(|dropped| dropped == *domain))
            .cloned()
            .collect();
        if !rest.is_empty() {
            kept.push(format_hosts_mapping_line(&ip, &rest, &comment));
        }
    }
    (kept, dropped)
}

/// Добавляет блок программы перед обычными строками hosts. Работает на
/// уже прочитанных строках файла (тип «keepends»).
pub fn insert_managed_hosts_block(
    new_lines: &mut Lines,
    rows: &Rows,
    insert_at: Option<usize>,
) {
    if rows.is_empty() {
        return;
    }
    let mut insert_at = match insert_at {
        Some(index) => index,
        None => new_lines
            .iter()
            .position(|line| parse_hosts_mapping_line(line).is_some())
            .unwrap_or(new_lines.len()),
    };
    insert_at = insert_at.min(new_lines.len());

    // Убираем пустые строки вокруг места вставки: блок зажимают
    // разделителями.
    while insert_at > 0 && new_lines[insert_at - 1].trim().is_empty() {
        new_lines.remove(insert_at - 1);
        insert_at -= 1;
    }
    while insert_at < new_lines.len() && new_lines[insert_at].trim().is_empty() {
        new_lines.remove(insert_at);
    }

    let mut block: Lines = Vec::new();
    if insert_at > 0 && !new_lines[insert_at - 1].trim().is_empty() {
        block.push("\n".to_string());
    }
    block.push(format!("{MANAGED_HOSTS_BEGIN}\n"));
    block.push(format!("{MANAGED_HOSTS_NOTICE}\n"));
    for (domain, ip) in rows {
        block.push(format!("{ip} {domain}\n"));
    }
    block.push(format!("{MANAGED_HOSTS_END}\n"));
    if insert_at < new_lines.len() && !new_lines[insert_at].trim().is_empty() {
        block.push("\n".to_string());
    }
    let tail = new_lines.split_off(insert_at);
    new_lines.extend(block);
    new_lines.extend(tail);
}

/// Русская «запись/записи/записей»: с рождения столько строк в блоке.
pub fn format_hosts_entries_count(count: usize) -> String {
    let count = count as i64;
    let word = if count % 10 == 1 && count % 100 != 11 {
        "запись"
    } else if count % 10 == 2 || count % 10 == 3 || count % 10 == 4 {
        if count % 100 == 12 || count % 100 == 13 || count % 100 == 14 {
            "записей"
        } else {
            "записи"
        }
    } else {
        "записей"
    };
    format!("{count} {word}")
}

/// Как `is_ipv6_address` из Python: адрес IPv6 или как обычно IPv4/плохой.
pub fn is_ipv6_address(ip: &str) -> bool {
    ip.trim()
        .parse::<std::net::IpAddr>()
        .is_ok_and(|addr| addr.is_ipv6())
}

/// Чистит строки перед записью: пустые, повторы и IPv6 без поддержки
/// IPv6. Возвращает (строки для записи, были ли вообще запрошены строки).
pub fn filter_desired_hosts_rows(rows: &Rows, allow_ipv6: bool) -> (Rows, bool) {
    let mut desired: Rows = Vec::new();
    let mut seen: std::collections::BTreeSet<(String, String)> =
        std::collections::BTreeSet::new();
    let mut had_requested_rows = false;
    for (domain, ip) in rows {
        let (domain, ip) = (domain.trim(), ip.trim());
        if domain.is_empty() || ip.is_empty() {
            continue;
        }
        had_requested_rows = true;
        if is_ipv6_address(ip) && !allow_ipv6 {
            continue;
        }
        let key = (lowered(domain), lowered(ip));
        if seen.contains(&key) {
            continue;
        }
        seen.insert(key);
        desired.push((domain.to_string(), ip.to_string()));
    }
    (desired, had_requested_rows)
}

/// Строки hosts для сравнения: у каждого имени — его адреса по порядку.
/// Важен порядок адресов одного имени (первый берёт браузер), порядок
/// самих имён не влияет: он зависит от того, как шли сервисы. Из-за
/// списочного сравнения hosts переписывался при первом же запуске
/// (стенд 2026-10-13); поэтому сверка — карта «имя → адреса».
pub fn hosts_rows_key(rows: &Rows) -> std::collections::BTreeMap<String, Vec<String>> {
    let mut key: std::collections::BTreeMap<String, Vec<String>> =
        std::collections::BTreeMap::new();
    for (domain, ip) in rows {
        key.entry(lowered(domain)).or_default().push(lowered(ip));
    }
    key
}

/// Решает, нужно ли при запуске переписать блок программы в hosts.
/// Блок переписывается, только если пользователь уже применял выбор
/// (блок есть и выбор сохранён), адреса отличаются от текущего каталога,
/// а IPv6-записи блока не встречают недоступный IPv6 (он мог ещё не
/// подняться при запуске — мы не выкидываем IPv6-записи по этой причине).
pub fn decide_applied_selection_refresh(
    block_rows: &Rows,
    has_saved_selection: bool,
    ipv6_available: bool,
    build_desired_rows: impl FnOnce() -> Rows,
) -> (bool, String) {
    if block_rows.is_empty() {
        return (false, "блока PrimeBypass в hosts нет".to_string());
    }
    if !has_saved_selection {
        return (false, "выбор сервисов не сохранён".to_string());
    }
    if !ipv6_available && block_rows.iter().any(|(_, ip)| is_ipv6_address(ip)) {
        return (
            false,
            "IPv6 сейчас недоступен, а в блоке есть IPv6-записи".to_string(),
        );
    }
    let desired_rows = build_desired_rows();
    if hosts_rows_key(&desired_rows) == hosts_rows_key(block_rows) {
        return (false, "адреса в hosts уже актуальны".to_string());
    }
    (true, "адреса в hosts устарели".to_string())
}
