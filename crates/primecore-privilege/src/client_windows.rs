//! Транспорт клиента на Windows.
//!
//! Постоянного демона-помощника на Windows нет: права там повышает UAC на
//! один процесс, а не `pkexec`/`sudo` с unix-сокетом. Поэтому клиент не
//! пытается соединиться, а отвечает понятной ошибкой — сервер покажет её
//! пользователю как «привилегии недоступны», вместо падения сборки.
//!
//! Если для Windows понадобится настоящий транспорт (named pipe или
//! loopback-порт с токеном), его место — здесь: заменить тело `connect`,
//! протокол в `client.rs` менять не придётся.

use std::time::Duration;

use super::Transport;

/// Соединения нет: демон привилегий на Windows не поддерживается.
///
/// # Errors
/// Всегда возвращает текст с причиной.
pub(super) fn connect(_sock_path: &str, _timeout: Duration) -> Result<Box<dyn Transport>, String> {
    Err("primecore-privilege: демон привилегий не поддерживается на Windows".to_string())
}
