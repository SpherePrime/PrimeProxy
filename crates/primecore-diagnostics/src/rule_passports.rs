#[cfg(test)]
mod tests {
    use super::*;

    /// python: паспорт для каждого вида; словарь полон и без лишних ключей.
    #[test]
    fn passports_full_python() {
        let rows = passports();
        assert_eq!(rows.len(), 16);
        for key in [
            bk::KIND_IP,
            bk::KIND_SNI,
            bk::KIND_CUT,
            bk::KIND_UNSTABLE,
            bk::KIND_STUB,
            bk::KIND_CERT,
            bk::KIND_UNCLEAR,
            bk::KIND_NO_CONNECT,
            bk::KIND_DOWN,
            bk::KIND_FINGERPRINT,
            bk::KIND_DNS,
            bk::KIND_QUIC,
            bk::KIND_VOICE,
            bk::KIND_NETWORK,
            bk::KIND_SYSTEM,
            bk::KIND_OTHER,
        ] {
            let row = rows
                .get(key)
                .unwrap_or_else(|| panic!("нет паспорта: {key}"));
            assert!(!row.claim.is_empty());
            assert!(!row.evidence.is_empty());
            assert!(!row.false_alarms.is_empty());
            assert!(!row.control.is_empty());
        }
        // Тексты сверены с python-эталоном.
        assert_eq!(
            rows.get(bk::KIND_IP).unwrap().claim,
            "Закрыт сам адрес сервера: соединение не проходит, каким именем его ни называй."
        );
        assert_eq!(
            rows.get(bk::KIND_CUT).unwrap().evidence,
            "Ответ начал приходить и оборвался внутри окна 12–36 КБ (diagnostics.limits.FREEZE_*); \
             запросы подряд по одному соединению замирают там же."
        );
        assert_eq!(
            rows.get(bk::KIND_SYSTEM).unwrap().control,
            "VPN считается мешающим только при маршруте через его адаптер; прокси не считается вовсе; \
             о перехвате говорит только установившееся соединение с 192.0.2.1 — молчание и отказ нормальны."
        );
    }

    /// Золотой тест: тексты passports сверены с python-эталоном целиком
    /// (`tests/rule_passports_golden.json` выгружен из `rule_passports.py`).
    #[test]
    fn passports_golden_python() {
        let rows = passports();
        let golden = serde_json::from_str::<serde_json::Value>(include_str!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/tests/rule_passports_golden.json"
        )))
        .unwrap();
        for (key, expected) in golden.as_object().unwrap() {
            let row = rows
                .get(key.as_str())
                .unwrap_or_else(|| panic!("нет паспорта: {key}"));
            let actual = serde_json::json!({
                "claim": row.claim,
                "evidence": row.evidence,
                "false_alarms": row.false_alarms,
                "control": row.control,
            });
            assert_eq!(&actual, expected, "расхождение в паспорте {key}");
        }
    }
}
