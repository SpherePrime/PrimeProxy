//! Порт `src/diagnostics/rule_passports.py` — паспорта выводов BlockCheck:
//! что каждый вид блокировки утверждает и почему ему можно верить.
//!
//! Вывод «сайт закрыт по адресу» или «режут по имени» человек принимает за
//! факт и по нему лечит. Поэтому у каждого вида блокировки
//! ([`crate::block_kind`]) здесь записано четыре вещи, по образцу «паспортов
//! сигналов» ByeByeVPN:
//!
//! - `claim` — что именно утверждает вывод;
//! - `evidence` — на каких фактах проверки он держится;
//! - `false_alarms` — когда такие же факты бывают без блокировки;
//! - `control` — что проверка делает, чтобы эти ложные тревоги отсечь.
//!
//! Паспорт — договор: меняется правило вывода — меняется и паспорт.

use std::collections::HashMap;
use std::sync::OnceLock;

use crate::block_kind as bk;

pub struct Passport {
    pub claim: &'static str,
    pub evidence: &'static str,
    pub false_alarms: &'static str,
    pub control: &'static str,
}

const fn passport(
    claim: &'static str,
    evidence: &'static str,
    false_alarms: &'static str,
    control: &'static str,
) -> Passport {
    Passport {
        claim,
        evidence,
        false_alarms,
        control,
    }
}

